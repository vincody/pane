import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createApp} from '../../server/src/app.ts';
import {serverPort} from '../helpers/http.ts';

test('Files decorates real Git changes and folders, clears clean and non-Git workspaces',async({page})=>{
 const temp=await fs.mkdtemp(path.join(os.tmpdir(),'pane-git-files-'));
 const root=path.join(temp,'repo'),plain=path.join(temp,'plain');
 await fs.mkdir(root);await fs.mkdir(plain);await fs.mkdir(path.join(root,'src'));
 const execute=promisify(execFile);
 const git=(args:string[])=>execute('git',args,{cwd:root,windowsHide:true});
 await fs.writeFile(path.join(root,'tracked.txt'),'before\n');
 await fs.writeFile(path.join(root,'clean.txt'),'clean\n');
 await fs.writeFile(path.join(root,'src','nested.txt'),'before\n');
 await fs.writeFile(path.join(plain,'tracked.txt'),'plain\n');
 await git(['init']);await git(['add','.']);
 await git(['-c','core.hooksPath='+path.join(temp,'no-hooks'),'-c','commit.gpgsign=false','-c','user.name=Pane Tests','-c','user.email=tests@example.invalid','commit','-m','fixture']);
 await fs.writeFile(path.join(root,'tracked.txt'),'modified\n');
 await fs.writeFile(path.join(root,'new.txt'),'untracked\n');
 await fs.writeFile(path.join(root,'src','nested.txt'),'modified\n');
 await fs.writeFile(path.join(root,'src','new.txt'),'untracked\n');
 const app=await createApp({initialRoot:root,stateDir:path.join(temp,'state'),agentHome:temp});
 await new Promise<void>(resolve=>app.server.listen(0,'127.0.0.1',resolve));
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/api/account-usage?**',route=>route.fulfill({json:{providers:[]}}));
 try{
  await page.goto(`http://127.0.0.1:${serverPort(app.server)}`);
  const row=(file:string)=>page.locator(`.file-row[data-path="${file}"]`);
  await expect(row('tracked.txt').locator('.file-git-status')).toHaveText('M');
  await expect(row('new.txt').locator('.file-git-status')).toHaveText('U');
  await expect(row('clean.txt').locator('.file-git-status')).toHaveCount(0);
  await expect(row('src').locator('.file-git-status')).toHaveText('●');
  await row('src').click();
  await expect(row('src/nested.txt').locator('.file-git-status')).toHaveText('M');
  await expect(row('src/new.txt').locator('.file-git-status')).toHaveText('U');
  const colors=await row('tracked.txt').evaluate(el=>({name:getComputedStyle(el.querySelector('.file-row-name')!).color,mark:getComputedStyle(el.querySelector('.file-git-status')!).color}));
  expect(colors.name).toBe(colors.mark);
  expect(await row('new.txt').locator('.file-row-name').evaluate(el=>getComputedStyle(el).color)).not.toBe(colors.name);
  await page.screenshot({path:'test-results/file-git-status.png'});
  await page.getByRole('tab',{name:'Changes',exact:false}).click();
  const tracked=page.locator('.changes-group[data-group=changes]'),untracked=page.locator('.changes-group[data-group=untracked]');
  await expect(tracked.locator('.changes-group-count')).toHaveText('2');
  await expect(untracked.locator('.changes-group-count')).toHaveText('2');
  const nested=page.getByRole('button',{name:'View diff: src/nested.txt',exact:true});
  await expect(nested.locator('.changed-file-name')).toHaveText('nested.txt');
  await expect(nested.locator('.changed-file-directory')).toHaveText('src');
  await expect(nested.locator('.change-added')).toHaveText('+1');
  await expect(nested.locator('.change-removed')).toHaveText('−1');
  await expect(nested.locator('.change-status')).toHaveText('M');
  await tracked.locator('summary').click();await expect(tracked).toHaveJSProperty('open',false);
  const refreshed=page.waitForResponse(response=>response.url().includes('/api/changes?')&&response.status()===200);
  await page.locator('#refresh-files').click();await refreshed;
  await expect(tracked).toHaveJSProperty('open',false);
  await tracked.locator('summary').click();
  await expect(tracked).toHaveJSProperty('open',true);
  await page.screenshot({path:'test-results/changes-layout.png'});
  await nested.click();await expect(page.locator('.monaco-diff-editor:visible')).toBeVisible();
  await page.locator('#unified-tabs [role=tab][aria-selected=true] .tab-close').click();
  await page.getByRole('tab',{name:'Files',exact:true}).click();
  await git(['add','new.txt']);await page.locator('#refresh-files').click();
  await expect(row('new.txt').locator('.file-git-status')).toHaveText('A');
  await git(['restore','tracked.txt','src/nested.txt']);await page.locator('#refresh-files').click();
  await expect(row('tracked.txt').locator('.file-git-status')).toHaveCount(0);
  await expect(row('src/nested.txt').locator('.file-git-status')).toHaveCount(0);
  await page.getByRole('button',{name:'Open folder',exact:true}).click();
  await page.getByLabel('Folder path',{exact:true}).fill(plain);
  await page.locator('#folder-form button[type=submit]').click();
  await expect(page.locator('.project-button.active .project-text')).toHaveText('plain');
  await expect(row('tracked.txt')).toBeVisible();
  await expect(page.locator('#tree .file-git-status')).toHaveCount(0);
  expect(errors).toEqual([]);
 }finally{
  await page.close();await app.closeSessions();await new Promise<void>(resolve=>app.server.close(()=>resolve()));
  await fs.rm(temp,{recursive:true,force:true,maxRetries:10,retryDelay:100});
 }
});
