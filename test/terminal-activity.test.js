import test from 'node:test';
import assert from 'node:assert/strict';
import {readTerminalActivity} from '../client/terminal-activity.js';
test('Claude OSC and permission/question screens follow its own signals',()=>{
 const read=(screen,state,title='')=>readTerminalActivity(screen,state,{agent:'claude',title});
 let state=read('Ready',undefined,'✳ Claude');
 state=read('Output',state,'◐ Refactoring');assert.equal(state.status,'working');
 state=read('Do you want to proceed?\n❯ 1. Yes\n2. No\nEsc to cancel',state,'◐ Refactoring');
 assert.equal(state.status,'blocked');assert.equal(state.completed,false);
 state=read('Ready',state,'✳ Refactoring');assert.equal(state.completed,false);
 state=read('Output',state,'⠋ Refactoring');
 state=read('Output',state,'Refactoring');assert.equal(state.completed,false);
 state=read('Ready',state,'✳ Refactoring');assert.equal(state.completed,true);
 assert.equal(read('MCP server "example" requests your input\n❯ Accept\nDecline\nEsc to cancel',state).status,'blocked');
 assert.equal(read('Choose an approach\nEnter to select · arrow keys to navigate · Esc to cancel',state).status,'blocked');
 assert.equal(read('✻ Waiting for 2 background agents to finish',state).status,'working');
 const picker=read('Select model\nEnter to set as default\nEsc to cancel',state,'✳ Claude');assert.equal(picker.completed,false);assert.equal(picker.status,state.status);
});
test('OSC titles distinguish action requests from real work completion',()=>{
 let state=readTerminalActivity('Ready',undefined,{title:'Codex'});
 state=readTerminalActivity('Output',{...state},{title:'⠋ Fix resizing',agent:'codex'});
 assert.equal(state.status,'working');
 state=readTerminalActivity('Question 1/1\nChoose a layout',state,{title:'[ ! ] Action Required | project',agent:'codex'});
 assert.equal(state.status,'blocked');assert.equal(state.completed,false);
 state=readTerminalActivity('Ready',state,{title:'Fix resizing',agent:'codex'});
 assert.equal(state.completed,false);
 state=readTerminalActivity('Working',state,{title:'⠙ Fix resizing',agent:'codex'});
 state=readTerminalActivity('Ready',state,{title:'Fix resizing',agent:'codex'});
 assert.equal(state.completed,true);
 assert.equal(readTerminalActivity('Ready',state,{title:'Fix resizing',agent:'codex'}).completed,false);
 const viewer=readTerminalActivity('↑/↓ to scroll · pgup/pgdn to navigate\nq to quit · esc to edit prev',state,{title:'[ ! ] Action Required'});
 assert.equal(viewer.status,state.status);assert.equal(viewer.completed,false);
 assert.equal(readTerminalActivity('Working',undefined,{title:'◐ Refactoring',agent:'claude'}).status,'working');
});
test('intermediate replies do not signal completion, final turn markers do',()=>{
 let state=readTerminalActivity('Ready');
 state=readTerminalActivity('⠋ Working · esc to interrupt',state);
 state=readTerminalActivity('I have updated the file. Next I will check it.',state);
 assert.equal(state.completed,false);
 state=readTerminalActivity('Worked for 8s · 10:20 PM\nAsk Codex to do anything',state);
 assert.equal(state.completed,true);
 assert.equal(readTerminalActivity('Worked for 8s · 10:20 PM',state).completed,false);
 assert.equal(readTerminalActivity('Worked for 8s · 10:20 PM').completed,false);
 const updating=readTerminalActivity('Worked for 10s · 10:21 PM\nesc to interrupt',state);
 assert.equal(updating.completed,false);
 assert.equal(readTerminalActivity('Worked for 10s · 10:21 PM\nReady',updating).completed,true);
 assert.equal(readTerminalActivity('Would you like to run this command?\n1. Yes',state).status,'blocked');
});
test('slash menus and historical completion redraws never notify',()=>{
 let state=readTerminalActivity('Ready');
 state=readTerminalActivity('› /\n/model Select model\n/permissions Configure approvals\nEnter to confirm · Esc to cancel',state);
 assert.equal(state.status,'idle');assert.equal(state.completed,false);
 state=readTerminalActivity('Worked for 8s · 10:20 PM\n› /\n/model Select model\n/permissions Configure approvals\nEnter to confirm',state);
 assert.equal(state.status,'idle');assert.equal(state.completed,false);
 state=readTerminalActivity('Worked for 8s · 10:20 PM\nReady',state);
 assert.equal(state.completed,false);
 assert.equal(readTerminalActivity('Enter to confirm · Esc to cancel',state).status,'idle');
 assert.equal(readTerminalActivity('Choose a response\nTab to switch questions\nType your answer',state).status,'blocked');
 assert.equal(readTerminalActivity('Would you like to run this command?\n1. Yes\nNo, and tell Codex what to do differently.',state).status,'blocked');
});
test('Codex questions outrank completion history and answering does not replay it',()=>{
 let state=readTerminalActivity('Ready');
 state=readTerminalActivity('Working · esc to interrupt',state);
 const panel='Worked for 8s · 10:20 PM\nQuestion 1/2 (2 unanswered)\nWhich approach?\n1. First\n2. Second\n3. None of the above\nEnter to submit | tab to add notes';
 state=readTerminalActivity(panel,state);
 assert.equal(state.status,'blocked');assert.equal(state.completed,false);
 state=readTerminalActivity(panel.replace('Question 1/2','Question 2/2'),state);
 assert.equal(state.status,'blocked');assert.equal(state.completed,false);
 state=readTerminalActivity('Worked for 8s · 10:20 PM\nAsk Codex to do anything',state);
 assert.equal(state.completed,false);
 state=readTerminalActivity('Worked for 8s · 10:20 PM\nAsk Codex to do anything',state);
 assert.equal(state.completed,false);
 state=readTerminalActivity('Working · esc to interrupt',state);
 state=readTerminalActivity('Worked for 12s · 10:22 PM\nReady',state);
 assert.equal(state.completed,true);
});
